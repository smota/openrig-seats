// Generates src/types.generated.ts from schemas/*.v1.schema.json. `--check` compares instead of writing.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const schemaDir = join(root, "schemas");
const outFile = join(root, "src/types.generated.ts");

const NAMES = {
  host: "Host", rig: "Rig", seat: "Seat", turn: "Turn", attention: "Attention", work: "Work",
  action: "DeclaredAction", "act-request": "ActRequest", "act-response": "ActResponse",
  terminal: "Terminal", "terminal-scroll": "TerminalScroll", capabilities: "Capabilities", "stream-envelope": "StreamEnvelope", "stream-control": "StreamControl",
  "x-openrig-seat": "XOpenrigSeat", "x-openrig-event": "XOpenrigEvent",
};

// The 2020-12 meta-schema is referenced by URL: type it locally instead of fetching it, and type
// the free-form wire values as arbitrary JSON.
const JSON_SCHEMA_TS = "boolean | { [k: string]: Json }";
function patch(node) {
  if (Array.isArray(node)) return node.forEach(patch);
  if (!node || typeof node !== "object") return;
  if (node.$ref === "https://json-schema.org/draft/2020-12/schema") { delete node.$ref; node.tsType = JSON_SCHEMA_TS; }
  for (const v of Object.values(node)) patch(v);
}
const defs = {};
for (const file of Object.keys(NAMES)) defs[NAMES[file]] = { $ref: `${file}.v1.schema.json` };
const rewritten = new Map(); // file path -> rewritten schema, applied through a custom resolver
for (const file of ["common", ...Object.keys(NAMES)]) {
  const schema = JSON.parse(readFileSync(join(schemaDir, `${file}.v1.schema.json`), "utf8"));
  patch(schema);
  if (file === "act-request") schema.properties.input.tsType = "Json";
  if (file === "act-response") schema.properties.result.tsType = "Json";
  rewritten.set(`${file}.v1.schema.json`, schema);
}
const ts = await compile(
  { title: "SeatProtocol", type: "object", $defs: defs },
  "SeatProtocol",
  { cwd: schemaDir + "/", bannerComment: "", additionalProperties: true, declareExternallyReferenced: true, unreachableDefinitions: true, format: false,
    $refOptions: { resolve: { file: { order: 1, canRead: /\.v1\.schema\.json$/, read: (file) => JSON.stringify(rewritten.get(file.url.split("/").pop())) } } } },
);
// Names come from schema titles ("Seat protocol v1: host"); make them plain and drop the empty root.
let body = ts.trim()
  .replace(/export interface SeatProtocol \{[^}]*\}\n*/, "")
  .replace(/\bSeatProtocolV1(POSTAct|GETCapabilities|\w)/g, (_m, x) => (x === "POSTAct" ? "Act" : x === "GETCapabilities" ? "Capabilities" : x));
let out = "// Generated by scripts/generate-types.mjs from schemas/*.v1.schema.json. Do not edit.\n/* eslint-disable */\n\nexport type Json = null | boolean | number | string | Json[] | { [k: string]: Json };\n\n" + body + "\n";

if (process.argv.includes("--check")) {
  const current = readFileSync(outFile, "utf8");
  if (current !== out) { console.error("types.generated.ts is stale: run npm run generate"); process.exit(1); }
  console.log("types.generated.ts is up to date");
} else {
  writeFileSync(outFile, out);
  console.log(`wrote ${outFile}`);
}
